create table sys_dept (
    id bigint generated by default as identity primary key,
    parent_id bigint references sys_dept(id) on delete restrict,
    name varchar(100) not null,
    sort_order integer not null default 0,
    status varchar(16) not null default 'ENABLED'
        check (status in ('ENABLED', 'DISABLED')),
    version integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (parent_id is null or parent_id <> id)
);

create table sys_user (
    id bigint generated by default as identity primary key,
    username varchar(32) not null unique,
    password_hash varchar(255) not null,
    nickname varchar(64) not null,
    dept_id bigint not null references sys_dept(id) on delete restrict,
    status varchar(16) not null default 'ENABLED'
        check (status in ('ENABLED', 'DISABLED')),
    protected_account boolean not null default false,
    auth_version bigint not null default 0,
    version integer not null default 0,
    created_by bigint,
    updated_by bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (username ~ '^[a-z][a-z0-9_]{2,31}$')
);

create table sys_role (
    id bigint generated by default as identity primary key,
    code varchar(64) not null unique,
    name varchar(100) not null,
    status varchar(16) not null default 'ENABLED'
        check (status in ('ENABLED', 'DISABLED')),
    data_scope varchar(32) not null
        check (data_scope in ('ALL', 'DEPT', 'DEPT_AND_CHILDREN', 'SELF')),
    built_in boolean not null default false,
    version integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table sys_menu (
    id bigint generated by default as identity primary key,
    parent_id bigint references sys_menu(id) on delete restrict,
    name varchar(100) not null,
    type varchar(16) not null check (type in ('DIRECTORY', 'PAGE', 'BUTTON')),
    route_name varchar(100) unique,
    path varchar(200),
    component_key varchar(100),
    permission_code varchar(100) unique,
    icon varchar(64),
    sort_order integer not null default 0,
    visible boolean not null default true,
    status varchar(16) not null default 'ENABLED'
        check (status in ('ENABLED', 'DISABLED')),
    version integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (parent_id is null or parent_id <> id),
    check (type = 'DIRECTORY' or permission_code is not null),
    check (type <> 'PAGE' or
        (route_name is not null and path is not null and component_key is not null))
);

create table sys_user_role (
    user_id bigint not null references sys_user(id) on delete cascade,
    role_id bigint not null references sys_role(id) on delete restrict,
    primary key (user_id, role_id)
);

create table sys_role_menu (
    role_id bigint not null references sys_role(id) on delete cascade,
    menu_id bigint not null references sys_menu(id) on delete restrict,
    primary key (role_id, menu_id)
);

create table sys_login_log (
    id bigint generated by default as identity primary key,
    user_id bigint,
    username varchar(32) not null,
    success boolean not null,
    reason_code varchar(64),
    ip varchar(64),
    user_agent varchar(512),
    trace_id varchar(64),
    created_at timestamptz not null default now()
);

create table sys_operation_log (
    id bigint generated by default as identity primary key,
    actor_id bigint,
    actor_username varchar(32),
    action varchar(100) not null,
    target_type varchar(64),
    target_id varchar(64),
    success boolean not null,
    error_code varchar(64),
    summary varchar(1000),
    trace_id varchar(64),
    duration_ms bigint not null,
    created_at timestamptz not null default now()
);

create index idx_dept_parent on sys_dept(parent_id);
create index idx_user_dept on sys_user(dept_id);
create index idx_user_role_role on sys_user_role(role_id);
create index idx_menu_parent on sys_menu(parent_id);
create index idx_role_menu_menu on sys_role_menu(menu_id);
create index idx_login_log_time on sys_login_log(created_at desc, id desc);
create index idx_operation_log_time on sys_operation_log(created_at desc, id desc);
