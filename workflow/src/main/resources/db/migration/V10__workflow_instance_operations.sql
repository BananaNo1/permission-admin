create table wf_instance_control (
    instance_id varchar(128) primary key
);

create table wf_instance_operation (
    id bigint generated by default as identity primary key,
    instance_id varchar(128) not null references wf_instance_control(instance_id),
    task_id varchar(128),
    actor_id bigint not null,
    target_id bigint,
    operation varchar(16) not null check (operation in ('TRANSFER', 'WITHDRAW', 'TERMINATE')),
    reason varchar(500) not null,
    created_at timestamp with time zone not null default current_timestamp
);

create index idx_wf_instance_operation_history on wf_instance_operation (instance_id, id desc);
create index idx_wf_instance_operation_actor on wf_instance_operation (instance_id, actor_id, operation);
