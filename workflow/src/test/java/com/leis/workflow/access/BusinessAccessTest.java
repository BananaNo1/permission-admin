package com.leis.workflow.access;

import org.mybatis.spring.SqlSessionFactoryBean;
import com.leis.workflow.access.mapper.BusinessMapper;
import com.leis.workflow.template.ReviewerDirectory;
import com.leis.workflow.template.mapper.ReviewerMapper;
import org.mybatis.spring.SqlSessionTemplate;
import java.util.List;
import com.leis.common.common.BusinessException;
import com.leis.permission.auth.ActorSnapshot;
import com.leis.permission.auth.CurrentActor;
import com.leis.permission.log.service.AuditService;
import com.leis.permission.log.dto.AuditCommand;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

import java.util.Set;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.Mockito.*;

class BusinessAccessTest {
    @Test
    void isolatesGrantsAndRevokesImmediately() throws Exception {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:scope;MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        var db = new JdbcTemplate(ds);
        db.execute("create table sys_user(id bigint primary key, nickname varchar not null, username varchar not null, status varchar not null)");
        db.execute("create table sys_menu(id bigint generated by default as identity primary key,parent_id bigint references sys_menu(id),name varchar,type varchar,route_name varchar,path varchar,component_key varchar,permission_code varchar, sort_order integer not null default 0)");
        new ResourceDatabasePopulator(new ClassPathResource("db/migration/V4__workflow_business.sql"),
                new ClassPathResource("db/migration/V7__approval_center_menus.sql")).execute(ds);
        assertThat(db.queryForList("select component_key from sys_menu where permission_code like 'workflow:inbox:%' order by sort_order",
                String.class)).containsExactly("workflow/tasks", "workflow/completed", "workflow/applications");
        assertThat(db.queryForObject("""
                select d.name from sys_menu p join sys_menu d on d.id=p.parent_id
                where p.component_key='workflow/templates' and p.type='PAGE'
                and d.type='DIRECTORY' and d.parent_id is null
                """, String.class)).isEqualTo("流程管理");
        db.update("insert into sys_user values (2,'甲%Editor','editor','ENABLED'),(3,'乙','disabled','DISABLED')");

        db.execute("create table sys_role(id bigint primary key, name varchar not null, code varchar not null, status varchar not null)");
        db.execute("create table sys_user_role(role_id bigint not null, user_id bigint not null)");
        db.update("insert into sys_role values (5,'采购经理','PURCHASING','ENABLED'),(6,'停用角色','DISABLED_ROLE','DISABLED')");
        db.update("insert into sys_user_role values (5,2),(5,3),(6,2)");

        var current = mock(CurrentActor.class);
        var admin = actor(1, true);
        var editor = actor(2, false);
        var audit = mock(AuditService.class);
        var factory = new SqlSessionFactoryBean();
        factory.setDataSource(ds);
        factory.setMapperLocations(new ClassPathResource("mapper/workflow/BusinessMapper.xml"),
                new ClassPathResource("mapper/workflow/ReviewerMapper.xml"));
        var session = new SqlSessionTemplate(factory.getObject());
        var access = new BusinessAccess(session.getMapper(BusinessMapper.class), current, audit);
        var reviewerMapper = session.getMapper(ReviewerMapper.class);
        var reviewers = new ReviewerDirectory(access, reviewerMapper);
        assertThat(reviewerMapper.activeRoleMembers(5, 1)).containsExactly(2L);
        assertThat(reviewerMapper.activeRoleMembers(5, 2)).isEmpty();
        assertThat(reviewerMapper.activeRoleMembers(6, 1)).isEmpty();
        when(current.get()).thenReturn(admin);
        access.create(new BusinessAccess.Create("a", "甲"));
        access.create(new BusinessAccess.Create("b", "乙"));
        assertThatThrownBy(() -> access.create(new BusinessAccess.Create("a", "重复")))
                .isInstanceOfSatisfying(BusinessException.class, e -> assertThat(e.getStatus()).isEqualTo(409));
        assertThat(access.list()).allMatch(business -> business.edit() && business.publish() && business.start());
        assertThatThrownBy(() -> access.require("missing", BusinessAccess.Capability.START)).isInstanceOf(BusinessException.class);
        access.grant("a", 2, new BusinessAccess.Rights(true, false, false));
        assertThat(access.grants("a")).containsExactly(new BusinessAccess.Grant(2L, true, false, false));
        when(current.get()).thenReturn(editor);
        access.require("a", BusinessAccess.Capability.VIEW_DRAFT);
        access.require("a", BusinessAccess.Capability.EDIT);
        assertThat(reviewers.roles("a")).extracting(ReviewerDirectory.RoleOption::id).containsExactly("5");
        assertThat(reviewers.find("a", "%", null)).extracting(ReviewerDirectory.Reviewer::id).containsExactly(2L);
        assertThat(reviewers.find("a", "EDITOR", null)).extracting(ReviewerDirectory.Reviewer::id).containsExactly(2L);
        assertThat(reviewers.find("a", "", null)).extracting(ReviewerDirectory.Reviewer::id).containsExactly(2L);
        assertThat(reviewers.find("a", "", List.of(3L))).containsExactly(
                new ReviewerDirectory.Reviewer(3L, "乙", "disabled", false));
        assertThatThrownBy(() -> reviewers.find("b", "", null)).isInstanceOf(BusinessException.class);
        assertThat(access.list()).extracting(BusinessAccess.Business::code).containsExactly("a");
        assertThatThrownBy(() -> access.require("a", BusinessAccess.Capability.PUBLISH)).isInstanceOf(BusinessException.class);
        assertThatThrownBy(() -> access.require("b", BusinessAccess.Capability.EDIT)).isInstanceOf(BusinessException.class);
        assertThatThrownBy(() -> access.grant("b", 2, new BusinessAccess.Rights(true, true, true))).isInstanceOf(BusinessException.class);
        when(current.get()).thenReturn(actor(3, false));
        assertThatThrownBy(() -> access.require("a", BusinessAccess.Capability.VIEW_DRAFT)).isInstanceOf(BusinessException.class);
        when(current.get()).thenReturn(admin);
        access.grant("a", 2, new BusinessAccess.Rights(false, true, false));
        when(current.get()).thenReturn(editor);
        access.require("a", BusinessAccess.Capability.VIEW_DRAFT);
        access.require("a", BusinessAccess.Capability.PUBLISH);
        assertThatThrownBy(() -> access.require("a", BusinessAccess.Capability.EDIT)).isInstanceOf(BusinessException.class);
        when(current.get()).thenReturn(admin);
        access.grant("a", 2, new BusinessAccess.Rights(false, false, false));
        when(current.get()).thenReturn(editor);
        verify(audit).success(new AuditCommand(1L, "user", "WORKFLOW_BUSINESS_CREATE", "WORKFLOW_BUSINESS", "a", true, "创建业务", null));
        verify(audit).success(new AuditCommand(1L, "user", "WORKFLOW_BUSINESS_GRANT", "WORKFLOW_BUSINESS", "a", true,
                "userId=2 edit=false publish=true start=false", null));
        verify(audit).success(new AuditCommand(1L, "user", "WORKFLOW_BUSINESS_REVOKE", "WORKFLOW_BUSINESS", "a", true,
                "userId=2 edit=false publish=false start=false", null));
        assertThat(access.list()).isEmpty();
        assertThatThrownBy(() -> access.require("a", BusinessAccess.Capability.VIEW_DRAFT)).isInstanceOf(BusinessException.class);
    }

    private ActorSnapshot actor(long id, boolean admin) {
        return new ActorSnapshot(id, "user", null, admin, Set.of(), false, Set.of(), false);
    }
}
